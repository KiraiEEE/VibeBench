"""
V2 JAVA -- full-pipeline verification. Run before trusting any number.

WHY THIS FILE EXISTS. The V2 Java run accumulated defects that each looked
harmless in isolation and each changed a published result:

  * a substring path filter that dropped 8,994 files, agent-biased
  * a tree-cache key that omitted that filter, making its fix a no-op
  * a calibration that read percentiles from a population the config did not
    describe
  * a merged-vs-rejected contrast confounded by reconstruction tier
  * machine-generated protobuf counted as agent code, which REORDERED the
    agents on SRP
  * a label sampler drawing from a population the report never publishes

Every one was found by a check, never by reading the code. So the checks live
in one runnable file rather than in a session's scrollback.

Exit code 0 = all pass, 1 = at least one FAIL. WARN never fails the run.

Run: python vibebench/07_verify/verify_v2_java.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config as C  # noqa: E402

FAILS: list[str] = []
WARNS: list[str] = []


def ok(msg: str) -> None:
    print(f"  [ok  ] {msg}")


def fail(msg: str) -> None:
    print(f"  [FAIL] {msg}")
    FAILS.append(msg)


def warn(msg: str) -> None:
    print(f"  [warn] {msg}")
    WARNS.append(msg)


def head(t: str) -> None:
    print("\n" + "=" * 70 + "\n" + t + "\n" + "=" * 70)


def is_bad(p) -> bool:
    """Not part of the reported population: test or machine-generated."""
    return C.is_test_path(str(p), "java") or C.is_generated_path(str(p))


PR = C.CORPUS_DIR / "java_pr_results.parquet"
ENT = {
    "srp": (C.SRP_RESULTS_JAVA, "srp_risk"),
    "ocp": (C.OCP_RESULTS_JAVA, "smell"),
    "isp": (C.ISP_RESULTS_JAVA, "flagged"),
    "lsp": (C.LSP_RESULTS_JAVA, "violation"),
}


def check_paths() -> None:
    head("A. ARTEFACTS EXIST")
    for name, p in [("pr", PR)] + [(k, v[0]) for k, v in ENT.items()]:
        if p.exists():
            ok(f"{name:<4} {p.name} ({p.stat().st_size / 1e6:.1f} MB)")
        else:
            fail(f"{name}: missing {p}")


def check_config() -> None:
    head("B. CONFIG: thresholds set, path rules not substring-based")
    t = C.SRP_JAVA_THRESHOLDS
    missing = [k for k in ("class_loc", "class_wmc", "class_methods", "func_ccn",
                           "func_params", "class_lcom", "min_hits")
               if t.get(k) is None]
    if missing:
        fail(f"SRP_JAVA_THRESHOLDS still None for {missing} -- calibration mode")
    else:
        ok(f"SRP thresholds set: loc={t['class_loc']} wmc={t['class_wmc']} "
           f"methods={t['class_methods']} lcom={t['class_lcom']} "
           f"min_hits={t['min_hits']}")

    bad_delta = {k: v for k, v in C.JAVA_DELTA_THRESHOLDS.items()
                 if any(x is None for x in v.values())}
    if bad_delta:
        fail(f"JAVA_DELTA_THRESHOLDS has None values: {bad_delta}")
    else:
        ok(f"delta thresholds set: {C.JAVA_DELTA_THRESHOLDS}")

    # These five are hand-written files whose NAMES contain a generated-looking
    # token. The first version of is_generated_path was a regex and matched all
    # of them; the same class of substring bug once dropped 8,994 Java files.
    traps = ["doma/src/main/java/AutoGeneratedKeysType.java",
             "maven/src/main/java/GenerateDaoMojo.java",
             "x/src/main/java/ProtobufJsonTranscoder.java",
             "riksdagen/src/main/java/A.java",
             "gradlebuild/src/main/java/B.java"]
    hit = [p for p in traps if C.is_generated_path(p)]
    (ok if not hit else fail)(
        f"is_generated_path rejects all {len(traps)} substring traps"
        if not hit else f"is_generated_path matches hand-written files: {hit}")

    real = ["proto/src/main/java/io/k8s/proto/V1Apps.java",
            "mlflow/java/client/src/main/java/org/mlflow/api/proto/Service.java",
            "a/src/main/java/generated/Foo.java"]
    miss = [p for p in real if not C.is_generated_path(p)]
    (ok if not miss else fail)(
        "is_generated_path catches real protoc output"
        if not miss else f"is_generated_path MISSES generated code: {miss}")


def check_pr_frame() -> pd.DataFrame:
    head("C. PR FRAME INTEGRITY")
    pr = pd.read_parquet(PR)
    okr = pr[pr.status == "ok"]
    n_dup = int(pr.pr_id.duplicated().sum())
    (ok if n_dup == 0 else fail)(f"pr_id unique ({n_dup} duplicates)")
    n_null = int(pr.outcome.isna().sum())
    (ok if n_null == 0 else fail)(f"outcome non-null ({n_null} nulls)")
    for col in ("after_sha", "before_sha"):
        n = int(okr[col].isna().sum())
        (ok if n == 0 else fail)(f"every analysable PR has {col} ({n} nulls)")
    (ok if okr.outcome.nunique() >= 2 else fail)(
        f"{okr.outcome.nunique()} outcomes in the analysable set")
    (ok if okr.agent.nunique() == 3 else fail)(
        f"{okr.agent.nunique()} agents present (expect 3)")
    print(f"         status : {pr.status.value_counts().to_dict()}")
    print(f"         tiers  : {okr.pair_tier.value_counts(dropna=False).to_dict()}")
    print(f"         outcome: {okr.outcome.value_counts().to_dict()}")
    return pr


def check_flag_sanity(pr: pd.DataFrame) -> None:
    head("D. FLAG SANITY (fires on everything or nothing = broken)")
    okr = pr[pr.status == "ok"]
    for name, col in (("OCP", "ocp_risk"), ("ISP", "isp_risk"),
                      ("LSP", "lsp_risk"), ("DIP", "dip_risk")):
        if col not in okr.columns:
            fail(f"{name}: column {col} missing")
            continue
        if okr[col].isna().all():
            fail(f"{name}: all-null -- harness still in calibration mode")
            continue
        r = okr[col].fillna(False).mean()
        k = int(okr[col].fillna(False).sum())
        if r in (0.0, 1.0):
            fail(f"{name}: degenerate flag rate {r:.0%}")
        elif r > 0.5:
            warn(f"{name}: flag rate {r:.1%} implausibly high")
        else:
            ok(f"{name}: {r:.1%} of analysable PRs ({k} flagged)")


def check_population_consistency() -> None:
    head("E. POPULATION: report and label sampler MUST agree")
    print("     The sampler had NO production filter until 2026-09-01, so every")
    print("     precision estimate would have described a different corpus than")
    print("     the one the thesis reports. This check exists to keep them tied.")
    for name, (path, flag) in ENT.items():
        if not path.exists():
            continue
        d = pd.read_parquet(path)
        if "row_type" in d.columns:
            d = d[d.row_type == "interface"] if name == "isp" else d[d.row_type != "pr"]
        if "file_path" not in d.columns:
            continue
        n_bad = int(d.file_path.map(is_bad).sum())
        ok(f"{name}: {len(d):,} entity rows, {n_bad:,} outside the reported "
           f"population ({n_bad / max(len(d), 1):.1%})")
        smp = C.LABELS_DIR / f"java_{name}_labeling_sample.csv"
        if smp.exists():
            s = pd.read_csv(smp)
            if "file_path" in s.columns:
                leak = int(s.file_path.map(is_bad).sum())
                (ok if leak == 0 else fail)(
                    f"{name}: label sample has {leak} out-of-population rows")


def check_label_samples() -> None:
    head("F. LABEL SAMPLES: blinded, balanced, unique")
    for name in list(ENT) + ["dip"]:
        smp = C.LABELS_DIR / f"java_{name}_labeling_sample.csv"
        if not smp.exists():
            warn(f"{name}: no sample drawn yet")
            continue
        s = pd.read_csv(smp)
        judge = f"llm_{name}_risk"
        if judge not in s.columns:
            fail(f"{name}: missing {judge} column for the judge to fill")
            continue
        if s[judge].notna().any():
            warn(f"{name}: {int(s[judge].notna().sum())} labels already filled")
        pred = ENT[name][1] if name in ENT else "dip_risk"
        bal = s[pred].value_counts().to_dict() if pred in s.columns else "?"
        dup = int(s.duplicated().sum())
        (ok if dup == 0 else fail)(
            f"{name}: {len(s)} rows, strata {bal}, {dup} duplicate rows")


def check_batches() -> None:
    head("G. BATCHES: the judge must NOT be able to see the verdict")
    leak_re = re.compile(
        r"\b(srp_risk|ocp_risk|isp_risk|lsp_risk|dip_risk|verdict|"
        r"smell\s*=\s*(true|false)|violation\s*=\s*(true|false)|"
        r"flagged\s*=\s*(true|false))\b", re.I)
    for name in list(ENT) + ["dip"]:
        d = C.LABELS_DIR / f"java_{name}_batches"
        if not d.exists():
            warn(f"{name}: not extracted yet")
            continue
        files = sorted(d.glob("*.txt"))
        if not files:
            warn(f"{name}: batch directory is empty")
            continue
        leaks = [f.name for f in files
                 if leak_re.search(f.read_text(encoding="utf-8", errors="replace"))]
        (ok if not leaks else fail)(
            f"{name}: {len(files)} batches, {len(leaks)} leak the verdict"
            + (f" e.g. {leaks[:3]}" if leaks else ""))
        un = sum(1 for f in files if "UNAVAILABLE" in f.name)
        if un:
            warn(f"{name}: {un}/{len(files)} batches UNAVAILABLE "
                 f"({un / len(files):.0%}) -- source could not be fetched")


def check_confound_controls(pr: pd.DataFrame) -> None:
    head("H. CONFOUND CONTROLS present and still necessary")
    okr = pr[pr.status == "ok"]
    t = okr[okr.outcome.isin(["merged", "rejected"])]
    x = pd.crosstab(t.outcome, t.pair_tier)
    print(x.to_string())
    if 1.0 in x.columns and int(x.loc["rejected", 1.0]) == 0 < int(x.loc["merged", 1.0]):
        ok("tier 1 is merged-only, so the raw merged-vs-rejected contrast is "
           "confounded by construction and the TIER-MATCHED one is mandatory")
    else:
        warn("tier 1 is not merged-only -- re-derive the tier-matched contrast")
    lo = okr.resolved_supertype_rate < 0.25
    hi = okr[~lo]
    changed = []
    for name, col in (("OCP", "ocp_risk"), ("ISP", "isp_risk"),
                      ("DIP", "dip_risk"), ("LSP", "lsp_risk")):
        if col not in okr.columns:
            continue
        order_all = okr.groupby("agent")[col].mean().sort_values(ascending=False).index.tolist()
        order_hi = hi.groupby("agent")[col].mean().sort_values(ascending=False).index.tolist()
        if order_all != order_hi:
            changed.append(name)
    ok(f"symbol resolution <25% on {int(lo.sum())} PRs ({lo.mean():.1%}); "
       f"they flag LESS, i.e. under-detection not false positives")
    (ok if not changed else warn)(
        "agent ranking is stable when low-resolution PRs are excluded"
        if not changed else f"agent ranking CHANGES for {changed} under resolution control")


def check_degenerate_pairs(pr: pd.DataFrame) -> None:
    head("J. DEGENERATE BEFORE/AFTER PAIRS (before == after)")
    print("     A pair where before == after diffs to nothing, and every layer")
    print("     above reads that emptiness as 'this PR touches no Java'. It cost")
    print("     ~700 analysable PRs before it was found on 2026-09-01.")
    okr = pr[pr.status == "ok"]
    same = okr[okr.before_sha == okr.after_sha]
    (ok if len(same) == 0 else fail)(
        f"no analysable PR has before_sha == after_sha ({len(same)} found)")
    empty = pr[pr.status == "no_touched_files"]
    if len(empty):
        import json as _json
        base = Path(C.EXTRACT_DIR_JAVA)
        bad = 0
        verified = 0
        for pid in empty.pr_id.astype(str):
            f = base / pid / "_touched.json"
            if not f.exists():
                continue
            try:
                if _json.loads(f.read_text()):
                    continue                      # non-empty: nothing to check
            except Exception:
                bad += 1
                continue
            # EMPTY. Legitimate only if GitHub itself answered for this PR.
            # `_verified.json` is written by fix_file_lists.py when the API
            # returned a COMPLETE file list containing no Java. Without that
            # marker an empty list is indistinguishable from the failed diff
            # that silently lost 2,948 PRs, so it stays a FAIL.
            if (base / pid / "_verified.json").exists():
                verified += 1
            else:
                bad += 1
        ok(f"{verified:,} PRs have an empty file list VERIFIED against GitHub "
           f"(a finding: the PR really touches no Java)")
        (ok if bad == 0 else fail)(
            f"no PR is dropped on an UNVERIFIED empty file list ({bad} found) -- "
            f"an empty raw diff is a resolution failure, never an answer")
    else:
        ok("no PR carries the no_touched_files status")


def check_stale() -> None:
    head("I. STALE ARTEFACTS must not sit beside V2 outputs")
    rep = Path(__file__).resolve().parents[1] / "04_report"
    loose = [p.name for p in rep.glob("*.csv")]
    (ok if not loose else fail)(
        "no V1 CSVs loose in 04_report"
        if not loose else f"{len(loose)} V1 CSVs still loose: {loose[:4]}")
    arch = rep / "V1_ARCHIVE"
    if arch.exists():
        ok(f"V1_ARCHIVE holds {len(list(arch.glob('*')))} quarantined files")
    else:
        warn("no V1_ARCHIVE directory")
    v2 = rep / "V2_java_report.txt"
    (ok if v2.exists() else warn)(
        f"V2 report saved in the repo ({v2.stat().st_size / 1e3:.0f} KB)"
        if v2.exists() else "V2 report not saved outside the temp scratchpad")


def main() -> None:
    print("V2 JAVA PIPELINE VERIFICATION")
    check_paths()
    check_config()
    pr = check_pr_frame()
    check_flag_sanity(pr)
    check_population_consistency()
    check_label_samples()
    check_batches()
    check_confound_controls(pr)
    check_degenerate_pairs(pr)
    check_stale()
    print("\n" + "=" * 70)
    print(f"RESULT: {len(FAILS)} FAIL, {len(WARNS)} warn")
    for f in FAILS:
        print(f"  FAIL: {f}")
    for w in WARNS:
        print(f"  warn: {w}")
    print("=" * 70)
    sys.exit(1 if FAILS else 0)


if __name__ == "__main__":
    main()
